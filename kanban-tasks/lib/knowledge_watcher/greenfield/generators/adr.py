"""adr.py — Tier JUDGMENT ADR generator (claude -p subprocess, parallel).

Per spec §9.4 + §9.5: each topic = 1 ADR via claude -p subprocess (Sonnet).
Parallel via ThreadPoolExecutor. 4 guardrails applied post-process.
W5: accepts optional CanonicalAdrScan for prefix-aware numbering.
"""
from __future__ import annotations

import re
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
from pathlib import Path
from typing import List, Optional, Set, Tuple

from lib.knowledge_watcher.greenfield.adr_canonical_scan import (
    CanonicalAdrScan, compose_adr_filename,
)

from lib.knowledge_watcher.greenfield import (
    ADRTopic, DocGenResult, SourceSignals, Tier,
)
from lib.knowledge_watcher.greenfield.claude_p import (
    run_claude_p, DEFAULT_MODEL,
)
from lib.knowledge_watcher.greenfield.guardrails import apply_4_guardrails


_ADR_FILENAME_RE = re.compile(r"^ADR-(\d+)-")
_ADR_COST_USD = 0.30  # conservative estimate for Sonnet via claude -p


def _next_adr_number(kb_root: Path, slug: str) -> int:
    adr_dir = kb_root / "30_adr" / slug
    if not adr_dir.is_dir():
        return 1
    existing: List[int] = []
    for p in adr_dir.glob("ADR-*.md"):
        m = _ADR_FILENAME_RE.match(p.name)
        if m:
            try:
                existing.append(int(m.group(1)))
            except ValueError:
                continue
    return (max(existing) + 1) if existing else 1


def _build_prompt(signals: SourceSignals, topic: ADRTopic, nnn: str) -> str:
    today = datetime.now(timezone.utc).date().isoformat()
    top_models = ", ".join(signals.schema_models[:10]) or "n/a"
    top_deps = ", ".join(f"{n}@{v}" for n, v in list(signals.deps.items())[:15]) or "n/a"
    top_services = ", ".join(signals.main_services[:5]) or "n/a"

    return f"""Você é um arquiteto de software. Gere uma ADR (Architecture Decision Record) para o tópico "{topic.title}" no projeto {signals.slug}, baseado nos sinais factuais abaixo.

CRÍTICO: NUNCA invente file paths, env vars, OR commit hashes. Refs em backticks SERÃO verificadas — se você cita `apps/foo.ts`, esse path DEVE estar em "Main services" abaixo. Se não souber, omita a referência ou diga "ver código fonte".

ADR number: {nnn} (use no título)
Slug: {signals.slug}

== Sinais factuais ==

Tech stack:
- Schema models ({len(signals.schema_models)}): {top_models}
- Top deps: {top_deps}
- Main services ({signals.services_count}): {top_services}
- Auth middleware: {signals.has_auth_middleware}
- Multi-tenancy (organizationId): {signals.has_org_id_pattern}

Topic detection rationale: {topic.rationale}
Confidence: {topic.confidence}

== Output esperado ==

Markdown apenas, em PT-BR (algumas seções em EN OK), estrutura:

# ADR-{nnn}: {topic.title}

**Status:** Proposta
**Data:** {today}
**Decisor:** TBD (review humano)
**Origem:** Auto-generated greenfield bootstrap

**Status history:**
- {today}: Proposta (auto-generated by F3)

## Contexto

<por que esta decisão importa NESTE projeto, derivado dos sinais>

## Decisão

<o que foi/seria decidido, derivado dos sinais — NÃO speculate>

## Alternativas consideradas

- `nome-alternativa` — razão de rejeição
- (apenas alternativas com evidência nos sinais; NÃO invente)

## Consequências

<positivas e negativas, derivadas>

---

> Status: Proposta — review humano obrigatório antes de Aceita.

NÃO use code fences ao redor do markdown final. NÃO escreva preâmbulo. Output direto.
"""


def _generate_one(
    signals: SourceSignals,
    topic: ADRTopic,
    nnn: int,
    *,
    dry_run: bool,
    filename_override: Optional[str] = None,
) -> DocGenResult:
    nnn_str = f"{nnn:03d}"
    if filename_override is not None:
        relative_path = f"30_adr/{signals.slug}/{filename_override}"
    else:
        relative_path = f"30_adr/{signals.slug}/ADR-{nnn_str}-{topic.slug}.md"

    if dry_run:
        return DocGenResult(
            tier=Tier.JUDGMENT,
            doc_type="adr",
            relative_path=relative_path,
            content=f"(dry-run skip — would generate ADR-{nnn_str}-{topic.slug})",
            cost_usd=0.0,
            warnings=["dry_run"],
        )

    prompt = _build_prompt(signals, topic, nnn_str)
    output = run_claude_p(prompt, model=DEFAULT_MODEL, timeout_s=300)

    if output is None:
        return DocGenResult(
            tier=Tier.JUDGMENT,
            doc_type="adr",
            relative_path=relative_path,
            content="",
            cost_usd=0.0,
            warnings=["claude -p returned None"],
        )

    content, warnings = apply_4_guardrails(output, signals, doc_type="adr")
    return DocGenResult(
        tier=Tier.JUDGMENT,
        doc_type="adr",
        relative_path=relative_path,
        content=content,
        cost_usd=_ADR_COST_USD,
        warnings=warnings,
    )


def generate_adrs(
    signals: SourceSignals,
    topics: List[ADRTopic],
    kb_root: Path,
    *,
    max_workers: int = 4,
    dry_run: bool = False,
    scan: Optional[CanonicalAdrScan] = None,  # W5: prefix-aware numbering
) -> List[DocGenResult]:
    """Generate one ADR per topic via parallel claude -p subprocesses.

    Returns list in same order as input topics.

    W5: if scan is provided, uses compose_adr_filename for prefix-aware
    numbering (e.g. MA-013-topic.md). Falls back to legacy _next_adr_number
    when scan=None (backward compat).
    """
    if not topics:
        return []

    # W5: prefer scan; fallback to legacy _next_adr_number
    if scan is not None:
        used_numbers: Set[int] = set()
        filenames = [compose_adr_filename(scan, t.slug, used_numbers) for t in topics]
        # Extract numeric portion from each filename for _generate_one nnn arg
        # (nnn used only for dry-run content string; filename_override wins for path)
        def _nnn_from_filename(fname: str) -> int:
            m = re.search(r"-(\d+)-", fname)
            return int(m.group(1)) if m else 0
        indexed: List[Tuple[int, ADRTopic, int, Optional[str]]] = [
            (i, topic, _nnn_from_filename(filenames[i]), filenames[i])
            for i, topic in enumerate(topics)
        ]
    else:
        # Legacy path (backward-compat): ADR-<NNN>-<slug>.md
        base = _next_adr_number(kb_root, signals.slug)
        indexed = [
            (i, topic, base + i, None)
            for i, topic in enumerate(topics)
        ]

    if dry_run or max_workers <= 1:
        # Synchronous path (also default for tests without threadpool)
        return [
            _generate_one(signals, topic, nnn, dry_run=dry_run, filename_override=fname)
            for _, topic, nnn, fname in indexed
        ]

    results: List[Optional[DocGenResult]] = [None] * len(topics)
    with ThreadPoolExecutor(max_workers=max_workers) as pool:
        future_to_idx = {
            pool.submit(
                _generate_one, signals, topic, nnn,
                dry_run=False, filename_override=fname,
            ): idx
            for idx, topic, nnn, fname in indexed
        }
        for fut in as_completed(future_to_idx):
            idx = future_to_idx[fut]
            try:
                results[idx] = fut.result()
            except Exception as e:
                _, topic, nnn, fname = indexed[idx]
                fallback_path = (
                    f"30_adr/{signals.slug}/{fname}"
                    if fname else
                    f"30_adr/{signals.slug}/ADR-{nnn:03d}-{topic.slug}.md"
                )
                results[idx] = DocGenResult(
                    tier=Tier.JUDGMENT,
                    doc_type="adr",
                    relative_path=fallback_path,
                    content="",
                    cost_usd=0.0,
                    warnings=[f"executor error: {type(e).__name__}: {e}"],
                )

    return [r for r in results if r is not None]
