"""draft_branch.py — push F3 bootstrap output to a draft branch in bevox-knowledge.

Per spec §9.4 and CLAUDE.md §7 (governance: draft/* for proposals, never auto-merge
to main canonical), F3 bootstrap-docs should land on a draft branch and surface a
review URL. This helper does the git ops (checkout -b → add → commit → push origin).

Contract:
- Branch naming: `draft/skill-v2-bootstrap-<slug>-<YYYY-MM-DD>` (date is push day)
- Idempotent: if branch exists locally and current HEAD matches, no-op; if branch
  exists with divergence, append commit on top
- Best-effort: returns Result (ok, branch, push_ok, error). Never raises — caller
  should treat dispatch failures as warnings, not blocking errors
- Always restores caller's original branch on success or failure
"""
from __future__ import annotations

import datetime as _dt
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional


@dataclass
class DraftBranchResult:
    ok: bool
    branch: Optional[str]
    push_ok: bool
    commit_sha: Optional[str]
    error: Optional[str]


def _run(args: List[str], cwd: Path, *, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(args, cwd=cwd, capture_output=True, text=True, check=check)


def _current_branch(repo: Path) -> Optional[str]:
    try:
        out = _run(["git", "rev-parse", "--abbrev-ref", "HEAD"], repo).stdout.strip()
        return out or None
    except subprocess.CalledProcessError:
        return None


def _has_changes(repo: Path) -> bool:
    out = _run(["git", "status", "--porcelain"], repo).stdout
    return bool(out.strip())


def push_to_draft_branch(
    kb_root: Path,
    slug: str,
    written_paths: List[Path],
    *,
    push_remote: bool = True,
    today: Optional[str] = None,
) -> DraftBranchResult:
    """Stage files, commit on a draft branch, optionally push to origin.

    `written_paths` are absolute paths inside `kb_root` that F3 just wrote.
    Restores caller's original branch on exit.
    """
    today = today or _dt.date.today().isoformat()
    branch = f"draft/skill-v2-bootstrap-{slug}-{today}"

    if not (kb_root / ".git").exists():
        return DraftBranchResult(
            ok=False, branch=None, push_ok=False, commit_sha=None,
            error=f"not a git repo: {kb_root}",
        )

    original = _current_branch(kb_root)
    if original is None:
        return DraftBranchResult(
            ok=False, branch=None, push_ok=False, commit_sha=None,
            error="cannot determine current branch (detached HEAD?)",
        )

    try:
        existing = _run(
            ["git", "rev-parse", "--verify", branch],
            kb_root, check=False,
        )
        branch_exists = existing.returncode == 0

        if branch_exists:
            _run(["git", "checkout", branch], kb_root)
        else:
            _run(["git", "checkout", "-b", branch], kb_root)

        rel_paths = []
        for p in written_paths:
            try:
                rel_paths.append(str(p.relative_to(kb_root)))
            except ValueError:
                continue

        if rel_paths:
            _run(["git", "add", "--"] + rel_paths, kb_root)

        if not _has_changes(kb_root):
            commit_sha = _run(["git", "rev-parse", "HEAD"], kb_root).stdout.strip()
            push_ok = False
            if push_remote:
                pr = _run(
                    ["git", "push", "-u", "origin", branch],
                    kb_root, check=False,
                )
                push_ok = pr.returncode == 0
            return DraftBranchResult(
                ok=True, branch=branch, push_ok=push_ok,
                commit_sha=commit_sha, error=None,
            )

        msg = (
            f"docs(skill-v2/F3): bootstrap canonical doc suite for {slug}\n\n"
            f"Auto-generated by F3 greenfield generator on {today}. Tier MECÂNICO\n"
            f"factual, Tier SEMI-AUTO Haiku draft, Tier JUDGMENT Sonnet (Status:\n"
            f"Proposta). Review humano + accept via /accept commands ou edit.\n\n"
            f"Files: {len(rel_paths)}\n"
        )
        _run(["git", "commit", "-m", msg], kb_root)
        commit_sha = _run(["git", "rev-parse", "HEAD"], kb_root).stdout.strip()

        push_ok = False
        if push_remote:
            pr = _run(
                ["git", "push", "-u", "origin", branch],
                kb_root, check=False,
            )
            push_ok = pr.returncode == 0

        return DraftBranchResult(
            ok=True, branch=branch, push_ok=push_ok,
            commit_sha=commit_sha, error=None,
        )

    except subprocess.CalledProcessError as e:
        return DraftBranchResult(
            ok=False, branch=branch, push_ok=False, commit_sha=None,
            error=f"git failed: {e.stderr.strip() or str(e)}",
        )
    finally:
        if original:
            _run(["git", "checkout", original], kb_root, check=False)
